import mesa
import numpy as np


class HematopoieticAgent(mesa.Agent):
    """
    Base class for Cells and Clones. Each agent holds `cpgs`, a 0/1 array of shape
    (n_genes, n_cpgs). Per-site rates live on the model (`model.rates`), never on the agent, so
    memory does not grow with the number of agents.

    Args:
        model: The AgingModel
        cpgs: Optional initial CpG state. Defaults to fully unmethylated. Creating an agent never
            draws random numbers; the founder's random initial pattern is generated by the model.
        lineage_id: Lineage label inherited by daughters. -1 until the end of the growth phase,
            when every surviving cell gets its own id.
        n_divisions: Number of divisions in this cell's history (parent and daughter are both
            incremented at every division).
        n_error_rounds: Number of rounds of replication errors applied to this cell's genome
            (equals n_divisions unless errors_on="daughter" or drift is time-based).
    """

    # (gain, loss) rate-array names used for per-step drift and for replication errors in each
    # drift mode. Overridden by Clone.
    STEP_RATES = ("p_meth", "p_unmeth")
    DIVISION_RATES = {"division": ("p_meth", "p_unmeth"), "both": ("p_meth_div", "p_unmeth_div")}

    def __init__(self, model, cpgs=None, lineage_id=-1, n_divisions=0, n_error_rounds=0):
        super().__init__(model)
        self.cpgs = np.zeros(model.rates.shape, dtype=int) if cpgs is None else cpgs
        self.lineage_id = lineage_id
        self.n_divisions = n_divisions
        self.n_error_rounds = n_error_rounds

    @property
    def n_genes(self):
        return self.cpgs.shape[0]

    @property
    def n_cpgs(self):
        return self.cpgs.shape[1]

    def rate_arrays(self):
        """Return the (gain, loss) per-step probability arrays that apply to this agent type."""
        rates = self.model.rates
        return tuple(getattr(rates, name) for name in self.STEP_RATES)

    def _flip(self, p_meth, p_unmeth):
        """One round of independent per-site gain/loss with a single uniform draw per site."""
        probs = self.model.rng.random(self.cpgs.shape)
        do_meth = (probs < p_meth) & (self.cpgs == 0)
        do_unmeth = (probs < p_unmeth) & (self.cpgs == 1)
        self.cpgs ^= do_meth | do_unmeth

    def methylate(self):
        """Apply one step of random methylation gain/loss to every CpG."""
        self._flip(*self.rate_arrays())

    def replicate_errors(self):
        """
        Apply one round of replication errors using this agent's division rates for the model's
        drift mode. Draws nothing when those rates are all zero (the round is still counted in
        n_error_rounds, so expected methylation follows beta_k with k = n_error_rounds).
        """
        names = self.DIVISION_RATES[self.model.drift_mode]
        self.n_error_rounds += 1
        rates = self.model.rates
        if rates.is_zero(*names):
            return
        self._flip(*(getattr(rates, name) for name in names))


class Cell(HematopoieticAgent):
    """A normal hematopoietic cell."""

    def duplicate(self):
        """Copy information from the parent Cell to the daughter cell. Used during growth phase."""
        self.model.copy_agent(self)

    def divide(self):
        """
        Neutral turnover after the growth phase: with probability p_turnover the cell divides and
        its daughter replaces a random agent (Moran step). No random number is drawn when
        p_turnover == 0, so turnover-free runs keep their original random stream.
        """
        p_turnover = self.model.p_turnover
        if p_turnover > 0 and self.model.rng.random() < p_turnover:
            self.model.birth(self)


class Clone(HematopoieticAgent):
    """
    A mutant Clone. Clone-specific per-site drift rates come from the model's rate profile, and
    division probabilities from the model.

    Each step a Clone divides with probability p_turnover + p_duplicate (its daughter replaces a
    random agent), dies with probability p_die (a copy of a random agent replaces it), and
    otherwise does nothing. Clones share the normal-cell turnover rate, so the selective advantage
    s = p_duplicate - p_die is relative to normal cells, and s = 0 is neutral at any p_turnover.
    """

    STEP_RATES = ("p_meth_clone", "p_unmeth_clone")
    DIVISION_RATES = {
        "division": ("p_meth_clone", "p_unmeth_clone"),
        "both": ("p_meth_div_clone", "p_unmeth_div_clone"),
    }

    def divide(self):
        """Execute one of the three outcomes (neutral, duplicate, die) as a Moran step."""
        m = self.model
        p_birth = m.p_turnover + m.p_duplicate
        division_type = m.rng.choice(
            ["neutral", "duplicate", "die"],
            p=[max(0.0, 1.0 - (m.p_turnover + m.p_duplicate + m.p_die)), p_birth, m.p_die],
        )

        if division_type == "duplicate":
            m.birth(self)
        elif division_type == "die":
            m.death(self)
